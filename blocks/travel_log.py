"""blocks/travel_log.py — the Travel Log Block, computed by code.

Selects `photo` and `place` events, groups them by `location.place` (events
with no place go under `Unplaced`), and writes one deterministic markdown
file. No model, no inference, no clock read inside `compute()`: the store
already resolves fixture rows to a `ts` before this module ever sees them.

Standard library only.
    python3 -m blocks.travel_log [--out PATH]
"""
from __future__ import annotations

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from vault import store  # noqa: E402

KINDS = ("photo", "place")
DEFAULT_OUT = os.path.join("blocks", "travel-log.md")


def _group_key(event: dict) -> str:
    place = ((event.get("location") or {}) or {}).get("place")
    return place if place else "Unplaced"


def compute(events: list[dict]) -> str:
    """Pure, deterministic. No clock, no randomness, no model."""
    selected = [e for e in events if e.get("kind") in KINDS]
    lines = [
        "<!-- generated by blocks/travel_log.py; never edit by hand -->",
        f"<!-- block: travel-log | records: {len(selected)} | kinds: photo, place -->",
        "# Travel Log",
        "",
    ]

    if not selected:
        lines.append(f"No trips in your records yet. Computed by code from {len(selected)} records.")
        return "\n".join(lines) + "\n"

    intro = (f"Places your photos and check-ins put you, grouped by place and day. "
             f"Computed by code from {len(selected)} records.")
    if any(e.get("fixture") for e in selected):
        intro += " Fixture data: none of it happened."
    lines.append(intro)

    groups: dict[str, list[dict]] = {}
    for e in selected:
        groups.setdefault(_group_key(e), []).append(e)

    def earliest(name: str) -> str:
        return min(e.get("ts") or "" for e in groups[name])

    for name in sorted(groups, key=lambda n: (earliest(n), n)):
        rows = sorted(groups[name], key=lambda e: (e.get("ts") or "", e.get("id") or ""))
        days = sorted({(e.get("ts") or "")[:10] for e in rows})
        span = days[0] if len(days) == 1 else f"{days[0]} to {days[-1]}"

        photos = sum(1 for e in rows if e.get("kind") == "photo")
        places = sum(1 for e in rows if e.get("kind") == "place")
        counts = []
        if photos:
            counts.append(f"{photos} photo" + ("s" if photos != 1 else ""))
        if places:
            counts.append(f"{places} place" + ("s" if places != 1 else ""))

        lines.append("")
        lines.append(f"## {name}")
        lines.append("")
        lines.append(f"- Days: {span}")
        lines.append(f"- Records: {', '.join(counts)}")
        for e in rows:
            ts = e.get("ts") or ""
            date, time = ts[:10], ts[11:16]
            lines.append(f"- {date} {time} {e.get('kind')} {e.get('title') or ''} ({e.get('id') or ''})")

    return "\n".join(lines) + "\n"


def write(out_path: str) -> str:
    """`compute(store.load_events())`, written to `out_path`. Returns the text."""
    text = compute(store.load_events())
    directory = os.path.dirname(out_path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    return text


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    text = write(args.out)
    match = re.search(r"records: (\d+)", text.splitlines()[1])
    records = match.group(1) if match else "0"
    print(f"travel-log: {records} records -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
