"""tests/test_blocks.py — the Travel Log Block, asserted.

Self-exiting script, the fleet convention: exit 0 is pass.

    python3 tests/test_blocks.py
"""
from __future__ import annotations

import os
import re
import sys
import tempfile

HOME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HOME)

from blocks import travel_log  # noqa: E402
from vault import store  # noqa: E402

PASS = FAIL = 0


def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  ok   {name}")
    else:
        FAIL += 1
        print(f"  FAIL {name}{(' — ' + str(detail)) if detail else ''}")


print("== the Travel Log Block ==")

events = store.load_events()
text = travel_log.compute(events)
lines = text.splitlines()

check("first two lines exact",
      lines[0] == "<!-- generated by blocks/travel_log.py; never edit by hand -->"
      and lines[1] == "<!-- block: travel-log | records: 3 | kinds: photo, place -->",
      lines[:2])
check("records: 3 with the shipped fixtures", "records: 3" in lines[1], lines[1])
check("one ## Bariloche, Rio Negro heading",
      sum(1 for l in lines if l == "## Bariloche, Rio Negro") == 1, lines)

row_lines = [l for l in lines if re.match(r"^- \d{4}-\d{2}-\d{2} \d{2}:\d{2} (photo|place) ", l)]
check("three record rows in ts order carrying the three ids",
      len(row_lines) == 3
      and row_lines[0].endswith("(ev-fixture-0012)")
      and row_lines[1].endswith("(ev-fixture-0010)")
      and row_lines[2].endswith("(ev-fixture-0011)"),
      row_lines)

days_line = next((l for l in lines if l.startswith("- Days:")), "")
check("Days: line spans two dates", days_line == "- Days: 2026-08-21 to 2026-08-22", days_line)

records_line = next((l for l in lines if l.startswith("- Records:")), "")
check("2 photos, 1 place", records_line == "- Records: 2 photos, 1 place", records_line)

check("two consecutive compute() calls are byte-identical",
      travel_log.compute(events) == travel_log.compute(events))

EMPTY_TEXT = (
    "<!-- generated by blocks/travel_log.py; never edit by hand -->\n"
    "<!-- block: travel-log | records: 0 | kinds: photo, place -->\n"
    "# Travel Log\n"
    "\n"
    "No trips in your records yet. Computed by code from 0 records.\n"
)
check("compute([]) equals the empty text in §3.3", travel_log.compute([]) == EMPTY_TEXT,
      travel_log.compute([]))

with tempfile.TemporaryDirectory() as tmp:
    out_path = os.path.join(tmp, "travel-log.md")
    written = travel_log.write(out_path)
    with open(out_path, encoding="utf-8") as f:
        on_disk = f.read()
    check("write() to a temp path produces a file equal to compute() of the store's events",
          written == travel_log.compute(store.load_events()) == on_disk)

committed_path = os.path.join(HOME, "blocks", "travel-log.md")
with open(committed_path, encoding="utf-8") as f:
    committed = f.read()
check("the committed blocks/travel-log.md starts with the generated header line",
      committed.startswith("<!-- generated by blocks/travel_log.py; never edit by hand -->"))
check("the committed blocks/travel-log.md contains records: 3 and the Bariloche heading",
      "records: 3" in committed and "## Bariloche, Rio Negro" in committed)

with open(os.path.join(HOME, "blocks", "travel_log.py"), encoding="utf-8") as f:
    src = "\n".join(l for l in f.read().splitlines() if not l.strip().startswith("#"))
BANNED = ("import requests", "import httpx", "import urllib", "import socket",
          "from urllib", "http.client", "subprocess.")
hits = [b for b in BANNED if b in src]
check("blocks/travel_log.py imports no network client and shells out to nothing", not hits, hits)

with open(os.path.join(HOME, "blocks", "travel_log.py"), encoding="utf-8") as f:
    src_full = f.read()
deletes = [w for w in ("os.remove(", "os.unlink(", "shutil.rmtree(", "os.rmdir(") if w in src_full]
check("blocks/travel_log.py deletes nothing", not deletes, deletes)

write_opens = re.findall(r"open\(([^,\n]+),\s*\"(a|w|ab|wb|a\+|w\+)\"", src_full)
bad = [t for t, _mode in write_opens if "out_path" not in t]
check("blocks/travel_log.py opens exactly one path for writing, named out_path",
      len(write_opens) == 1 and not bad, write_opens)

print(f"\n{PASS} passed, {FAIL} failed")
sys.exit(1 if FAIL else 0)
