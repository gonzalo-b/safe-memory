/** Real Next -> Python pairing; native client is synthetic API traffic, not an iPhone. */
import { createHash, randomBytes } from 'node:crypto';
import { expect, test } from '@playwright/test';
const username = process.env.MEMORY_TEST_USERNAME;
const password = process.env.MEMORY_TEST_PASSWORD;
if (!username || !password) throw new Error('Set synthetic MEMORY_TEST_USERNAME and MEMORY_TEST_PASSWORD.');

test('real owner confirmation and revocation of a synthetic native client', async ({ page, request }, info) => {
  await page.goto('/sources');
  await page.getByRole('textbox', { name: 'Username' }).fill(username);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sources', exact: true })).toBeVisible();
  const session = await (await page.request.get('/api/session')).json();
  expect(session.fixture).toBe(true);
  await page.getByRole('button', { name: 'Connect iPhone', exact: true }).click();
  const secretElement = page.locator('[aria-label="Temporary pairing code"] .memory-fingerprint');
  await expect(secretElement).toBeVisible();
  const secret = (await secretElement.innerText()).trim();
  const credential = randomBytes(32).toString('base64url');
  const fingerprint = createHash('sha256').update(credential).digest('hex');
  const deviceName = `Synthetic ${info.project.name} iPhone`;
  const claimResponse = await request.post('/api/device/claim', { data: { secret, credential, device_name: deviceName, library_id: 'synthetic-web-pairing-library' } });
  expect(claimResponse.status()).toBe(200);
  const claim = await claimResponse.json(); expect(claim.fingerprint).toBe(fingerprint);
  const status = () => request.post('/api/device/status', { headers: { Authorization: `Bearer ${credential}` }, data: { device_id: claim.claim_id } });
  expect((await status()).status()).toBe(401);
  await page.getByRole('button', { name: 'Refresh devices', exact: true }).click();
  const pending = page.getByRole('article', { name: `Device request: ${deviceName}` });
  await expect(pending.getByText(fingerprint, { exact: true })).toBeVisible();
  await expect(pending.getByRole('button', { name: 'Confirm device' })).toBeDisabled();
  await pending.getByRole('checkbox', { name: 'I compared the full fingerprint and device name' }).click();
  await pending.getByRole('button', { name: 'Confirm device' }).click();
  const registered = page.getByRole('article', { name: `Registered device: ${deviceName}` });
  await expect(registered.getByText('Registered', { exact: true })).toBeVisible();
  await expect(page.getByText('awaiting_ingest', { exact: true })).toBeVisible();
  await expect(page.getByText('restricted', { exact: true })).toBeVisible();
  const active = await status(); expect(active.status()).toBe(200);
  expect((await active.json()).data_access).toBe(false);
  await expect(secretElement).toHaveCount(0);
  expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])).toEqual(['{}','{}']);
  await page.reload(); await expect(registered.getByText('Registered', { exact: true })).toBeVisible();
  await registered.getByRole('button', { name: 'Revoke device', exact: true }).click();
  await registered.getByRole('button', { name: 'Confirm revocation', exact: true }).click();
  await expect(registered.getByText('Revoked', { exact: true })).toBeVisible();
  expect((await status()).status()).toBe(401);
  await registered.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('synthetic-device-revoked.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to Memory' })).toBeVisible();
});
